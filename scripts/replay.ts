// Replays 12 months of real GB grid data and writes src/replay.json (used by the site)
// and docs/REPLAY.md (the evidence). Run: npm run replay
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { clean, replay, replayByMonth } from '../src/backtest.ts';
import { APPLIANCES } from '../src/appliances.ts';

const hist = JSON.parse(readFileSync('data/gb-history.json', 'utf8'));
const c = clean(hist);
const r1 = (x: number) => Math.round(x * 10) / 10;
const fmt = (r: ReturnType<typeof replay>) => ({
  days: r.days, habitMean: r1(r.habitMean), shiftedMean: r1(r.shiftedMean), hindsightMean: r1(r.hindsightMean),
  cutPct: r1(r.cutPct), hindsightCutPct: r1(r.hindsightCutPct), daysBetterPct: r1(r.daysBetterPct), meanWaitHours: r1(r.meanWaitHours),
});
const HABITS = [{ label: '19:00, done by 07:00', habitStart: 19 * 60, windowHours: 12 },
  { label: '19:00, done within 24 h', habitStart: 19 * 60, windowHours: 24 },
  { label: '18:00, done by 07:00', habitStart: 18 * 60, windowHours: 13 },
  { label: '21:00, done by 07:00', habitStart: 21 * 60, windowHours: 10 },
  { label: '08:00, done by 18:00', habitStart: 8 * 60, windowHours: 10 }];
const rows = APPLIANCES.map((a) => ({
  id: a.id, name: a.name, kWh: a.kWh, slots: a.slots, perWeek: a.perWeek,
  habits: HABITS.map((h) => ({ ...h, ...fmt(replay(c, a.slots, h)) })),
}));
const main = HABITS[0];
const dish = APPLIANCES[0];
const months = replayByMonth(c, dish.slots, main).map((m) => ({ month: m.month, habitMean: r1(m.habitMean), shiftedMean: r1(m.shiftedMean), cutPct: r1(m.cutPct) }));
const first = new Date(c.start).toISOString().slice(0, 10);
const last = new Date(c.start + (c.actual.length - 1) * 18e5).toISOString().slice(0, 10);
const out = { period: { from: first, to: last, slots: c.actual.length, repairedSlots: c.repaired.length }, appliances: rows, months };
writeFileSync('src/replay.json', JSON.stringify(out, null, 1));

let md = `# Replay: does waiting for the cleanest hours really cut CO2?\n\n`;
md += `Generated by \`npm run replay\` from \`data/gb-history.json\`: ${c.actual.length} half-hours of Great Britain national carbon intensity, ${first} to ${last}, `;
md += `from the NESO Carbon Intensity API (CC BY 4.0). ${c.repaired.length} half-hour(s) repaired (an actual of 0 g while the forecast said 62 g; the forecast value is used).\n\n`;
md += `Method: every day, the appliance could start at the habit time. Grid Tide picks the start inside the window from the **forecast**; both runs are then scored on the **actual** intensity (NESO's after-the-fact estimate, not the forecast). "Hindsight" is the best start knowing the actuals (an upper bound).\n\n`;
for (const r of rows) {
  md += `## ${r.name} (${r.kWh} kWh, ${r.slots / 2} h)\n\n| Habit and window | Days | Habit g/kWh | Shifted g/kWh | Cut | Hindsight cut | Days cleaner | Mean wait |\n|---|---|---|---|---|---|---|---|\n`;
  for (const h of r.habits) md += `| ${h.label} | ${h.days} | ${h.habitMean} | ${h.shiftedMean} | **${h.cutPct}%** | ${h.hindsightCutPct}% | ${h.daysBetterPct}% | ${h.meanWaitHours} h |\n`;
  md += '\n';
}
md += `## ${dish.name}, ${main.label}, by month\n\n| Month | Habit g/kWh | Shifted g/kWh | Cut |\n|---|---|---|---|\n`;
for (const m of months) md += `| ${m.month} | ${m.habitMean} | ${m.shiftedMean} | ${m.cutPct}% |\n`;
md += `\n## Limits\n\n- The history keeps the last forecast made for each half-hour. A forecast made at 19:00 for 03:00 is less accurate, so live savings can be a little lower than the "Cut" column (the gap between Cut and Hindsight shows how much forecast error costs).\n- Intensity here is the **average** of the grid mix. The CO2 a shifted load really avoids depends on the **marginal** plant, which is usually gas in GB at peak times; at windy night-time hours some of the extra demand is met by wind that would otherwise be curtailed. Average intensity is the standard public signal (it is what the NESO API and most smart tariffs use), but treat the kg figures as an estimate, not a meter reading.\n- National series only: regional history has no actual values.\n`;
mkdirSync('docs', { recursive: true });
writeFileSync('docs/REPLAY.md', md);
console.log(JSON.stringify(rows.map((r) => [r.name, r.habits[0].cutPct, r.habits[0].daysBetterPct]), null, 0));
